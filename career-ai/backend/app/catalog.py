"""Loads the canonical catalog exported from the frontend dataset.

`app/data/careers.json` is generated by `backend/tools/export_catalog.py` from
`careers-data.js`, so the site and the API share one source of career content.
"""

from __future__ import annotations

import json
from functools import lru_cache
from typing import Any

from .config import DATA_FILE


@lru_cache(maxsize=1)
def catalog() -> dict[str, Any]:
    with DATA_FILE.open(encoding="utf-8") as handle:
        return json.load(handle)


def careers() -> list[dict[str, Any]]:
    return catalog()["careers"]


def meta() -> dict[str, Any]:
    return catalog()["meta"]


def career_by_id(career_id: str) -> dict[str, Any] | None:
    return next((career for career in careers() if career["id"] == career_id), None)


@lru_cache(maxsize=1)
def label_maps() -> dict[str, dict[str, str]]:
    data = meta()
    return {
        "skills": data["skillLabels"],
        "interests": data["interestLabels"],
        "workStyles": data["workStyleLabels"],
        "subjects": data["subjectLabels"],
    }


@lru_cache(maxsize=1)
def valid_keys() -> dict[str, frozenset[str]]:
    maps = label_maps()
    return {name: frozenset(values) for name, values in maps.items()}


@lru_cache(maxsize=1)
def education_values() -> frozenset[str]:
    return frozenset(level["value"] for level in meta()["educationLevels"])


@lru_cache(maxsize=1)
def branch_values() -> frozenset[str]:
    return frozenset(branch["value"] for branch in meta()["branches"])


@lru_cache(maxsize=1)
def branch_labels() -> dict[str, str]:
    return {branch["value"]: branch["label"] for branch in meta()["branches"]}
